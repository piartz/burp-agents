#!/usr/bin/env python3
"""Generate Claude Code and Codex agents from shared Markdown (Python 3.11+)."""

import argparse
import json
from pathlib import Path
import re
import sys
import tomllib

from burp_common import PROFILES


ROOT = Path(__file__).resolve().parents[1]
FIELDS = {"name", "description", "claude_model", "tools"}


def render(source):
    """Read the intentionally limited frontmatter: one unquoted scalar per line."""
    text = source.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError(f"{source}: missing frontmatter")
    header, separator, body = text[4:].partition("\n---\n")
    if not separator or not body.strip():
        raise ValueError(f"{source}: missing frontmatter terminator or instructions")
    metadata = {}
    for line in header.splitlines():
        key, separator, value = line.partition(": ")
        if not separator or key not in FIELDS or key in metadata or not value.strip():
            raise ValueError(f"{source}: invalid metadata line: {line!r}")
        metadata[key] = value.strip()
    if metadata.keys() != FIELDS:
        raise ValueError(f"{source}: expected fields {sorted(FIELDS)}")
    name = metadata["name"]
    if not re.fullmatch(r"[a-z][a-z0-9-]*", name) or name != source.stem:
        raise ValueError(f"{source}: name must match the filename and use kebab-case")
    tools = [tool.strip() for tool in metadata["tools"].split(",")]
    if any(not re.fullmatch(r"[a-z][a-z0-9_]*", tool) for tool in tools):
        raise ValueError(f"{source}: tools must be comma-separated server-side names")
    body = body.strip() + "\n"
    notice = f"Generated from agents/{source.name}; edit the source and run python3 scripts/sync-agents.py."
    tool_policy = (
        "Use only these Burp MCP capabilities for this task: " + ", ".join(tools)
        + ". This is an instruction boundary, not a permission sandbox.\n\n"
    )
    shared = (ROOT / "agents" / "_shared" / "contract.md").read_text(encoding="utf-8").strip()
    instructions = tool_policy + shared + "\n\n" + body
    claude = (
        "---\n"
        f"name: {json.dumps(name)}\n"
        f"description: {json.dumps(metadata['description'], ensure_ascii=False)}\n"
        f"model: {json.dumps(metadata['claude_model'])}\n"
        "tools: " + ", ".join(f"mcp__burp__{tool}" for tool in tools) + "\n"
        "---\n\n"
        f"<!-- {notice} -->\n\n" + instructions
    )
    # Prefer readable multiline instructions; fall back if a literal delimiter occurs.
    delimiter = "'" * 3
    encoded_instructions = (
        json.dumps(instructions, ensure_ascii=False)
        if delimiter in instructions
        else f"{delimiter}\n{instructions}{delimiter}"
    )
    codex = (
        f"# {notice}\n"
        f"name = {json.dumps(name)}\n"
        f"description = {json.dumps(metadata['description'], ensure_ascii=False)}\n"
        "# Model and reasoning effort inherit from the parent session.\n"
        f"developer_instructions = {encoded_instructions}\n"
    )
    assert tomllib.loads(codex)["developer_instructions"] == instructions
    return {
        ROOT / ".claude" / "agents" / f"{name}.md": claude,
        ROOT / ".codex" / "agents" / f"{name}.toml": codex,
    }


def render_profiles():
    outputs = {}
    for profile, capabilities in PROFILES.items():
        arguments = ["scripts/burp-gateway.py", "--engagement", "engagement.toml", "--profile", profile]
        claude = json.dumps({"mcpServers": {"burp": {"command": "python3", "args": arguments}}}, indent=2) + "\n"
        codex = (
            "# Generated by scripts/sync-agents.py. Run from the repository root.\n"
            "# Requires a local engagement.toml copied from config/engagement.example.toml.\n"
            f"# Profile: {profile}; choose the other template to change capabilities.\n"
            "[mcp_servers.burp]\ncommand = \"python3\"\n"
            f"args = {json.dumps(arguments)}\n"
            "startup_timeout_sec = 30\ntool_timeout_sec = 60\n"
            f"enabled_tools = {json.dumps(capabilities)}\n"
        )
        tomllib.loads(codex)
        outputs[ROOT / "config" / "mcp" / f"claude-{profile}.json"] = claude
        outputs[ROOT / "config" / "mcp" / f"codex-{profile}.toml"] = codex
        if profile == "analysis":
            outputs[ROOT / ".mcp.json"] = claude
            outputs[ROOT / "docs" / "codex-config.toml"] = codex
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated agents are missing or stale.")
    args = parser.parse_args()
    sources = sorted((ROOT / "agents").glob("*.md"))
    if not sources:
        parser.error("No shared agent definitions found")
    outputs = render_profiles()
    try:
        for source in sources:
            outputs.update(render(source))
    except ValueError as exc:
        parser.error(str(exc))
    stale = []
    for destination, content in outputs.items():
        if destination.exists() and destination.read_text(encoding="utf-8") == content:
            continue
        stale.append(destination.relative_to(ROOT))
        if not args.check:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(content, encoding="utf-8")
    if args.check and stale:
        print("Generated agents need updating: " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Synced'} {len(outputs)} files from {len(sources)} agents and shared profiles.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
